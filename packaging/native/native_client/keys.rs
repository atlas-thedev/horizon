/// `Keys.name`: a short label for a key (W, LMB, Space, LShift…).
pub fn name(code: i32) -> String {
    let fixed = match code {
        -1 => "None",
        0 => "LMB",
        1 => "RMB",
        2 => "MMB",
        3 => "M4",
        4 => "M5",
        32 => "Space",
        256 => "Esc",
        257 => "Enter",
        258 => "Tab",
        259 => "Backspace",
        280 => "Caps",
        340 => "LShift",
        341 => "LCtrl",
        342 => "LAlt",
        344 => "RShift",
        345 => "RCtrl",
        346 => "RAlt",
        260 => "Insert",
        261 => "Delete",
        262 => "Right",
        263 => "Left",
        264 => "Down",
        265 => "Up",
        266 => "PgUp",
        267 => "PgDn",
        268 => "Home",
        269 => "End",
        281 => "ScrLk",
        282 => "NumLk",
        283 => "PrtSc",
        284 => "Pause",
        330 => "Num .",
        331 => "Num /",
        332 => "Num *",
        333 => "Num -",
        334 => "Num +",
        335 => "Num Enter",
        336 => "Num =",
        343 => "LWin",
        347 => "RWin",
        348 => "Menu",
        39 => "'",
        44 => ",",
        45 => "-",
        46 => ".",
        47 => "/",
        59 => ";",
        61 => "=",
        91 => "[",
        92 => "\\",
        93 => "]",
        96 => "`",
        161 => "World 1",
        162 => "World 2",
        _ => "",
    };
    if !fixed.is_empty() {
        return fixed.to_owned();
    }
    match code {
        5..=7 => format!("M{}", code + 1),
        290..=314 => format!("F{}", code - 289),
        320..=329 => format!("Num {}", code - 320),
        65..=90 | 48..=57 => char::from_u32(code as u32).map_or_else(String::new, String::from),
        _ => format!("Key {code}"),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn keys_map_to_glfw_and_read_like_the_java_mod() {
        assert_eq!(glfw(KeyCode::KeyA), Some(65));
        assert_eq!(glfw(KeyCode::KeyZ), Some(90));
        assert_eq!(glfw(KeyCode::ShiftRight), Some(344));
        assert_eq!(glfw(KeyCode::F12), Some(301));
        assert_eq!(name(344), "RShift");
        assert_eq!(name(87), "W");
        assert_eq!(name(295), "F6");
        assert_eq!(name(500), "Key 500");
    }
}
